/**
 * Combined array of all locations
 * This is the complete dataset for seeding the database
 */
export const allLocations: LocationData[] = [
  ...counties,
  ...countyCapitals,
  ...bucharestSectors,
  ...majorCities,
];

/**
 * Helper function to get all locations by type
 */
export function getLocationsByType(type: "county" | "city" | "sector"): LocationData[] {
  return allLocations.filter((loc) => loc.type === type);
}

/**
 * Helper function to get all cities in a county
 */
export function getCitiesByCounty(countyId: string): LocationData[] {
  return allLocations.filter((loc) => loc.type === "city" && loc.parentId === countyId);
}

/**
 * Helper function to get all sectors in Bucharest
 */
export function getBucharestSectors(): LocationData[] {
  return allLocations.filter(
    (loc) => loc.type === "sector" && loc.parentId === "loc_city_bucuresti"
  );
}
